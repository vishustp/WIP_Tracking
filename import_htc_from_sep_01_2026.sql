      OR UPPER(TRIM(wo.work_order_no)) = UPPER('DOM-' || LPAD(TRIM(t.work_order_no), 5, '0'))
      OR UPPER(TRIM(REPLACE(wo.work_order_no, 'DOM-', ''))) = UPPER(TRIM(REPLACE(t.work_order_no, 'DOM-', '')))
      OR UPPER(TRIM(REPLACE(wo.work_order_no, 'DOM-BHEL-', 'DOM-'))) = UPPER(TRIM(REPLACE(t.work_order_no, 'DOM-BHEL-', 'DOM-')))
      OR UPPER(TRIM(REPLACE(wo.work_order_no, 'DOM-BHEL-', ''))) = UPPER(TRIM(REPLACE(t.work_order_no, 'DOM-BHEL-', '')))
    )
  LOOP
    PERFORM public.recalculate_work_order_wip(r.id);
  END LOOP;
END $body$;

