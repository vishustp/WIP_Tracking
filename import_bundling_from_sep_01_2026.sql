  work_order_id,
  stage_id,
  process_route_id,
  process_date,
  input_qty,
  output_qty,
  rejection_qty,
  htc_ok,
  heat_lot_no,
  remarks
)
SELECT
  wo.id AS work_order_id,
  (SELECT id FROM public.process_stages WHERE stage_code = 'FINISHING' LIMIT 1) AS stage_id,
  COALESCE(
    (SELECT rp.process_route_id FROM public.rolling_plans rp WHERE rp.work_order_id = wo.id ORDER BY rp.created_at DESC LIMIT 1),
    (SELECT pr.id FROM public.process_routes pr WHERE pr.route_code = 'CDS' LIMIT 1)
  ) AS process_route_id,
  t.process_date,
  t.mtr AS input_qty,
  t.mtr AS output_qty,
  0 AS rejection_qty,
  0 AS htc_ok,
  t.heat_lot_no,
  TRIM(COALESCE('Bundle: ' || t.bundle_no || ' Line: ' || t.work_center || ' Shift: ' || t.shift || ' ' || COALESCE(t.remarks, ''), '') || ' [PCS:' || t.pcs || '] [REJ_PCS:0]') AS remarks
FROM temp_bundling_import t
JOIN public.work_orders wo ON (
  UPPER(TRIM(wo.work_order_no)) = UPPER(TRIM(t.work_order_no))
  OR UPPER(TRIM(wo.work_order_no)) = UPPER('DOM-' || LPAD(TRIM(t.work_order_no), 5, '0'))
  OR UPPER(TRIM(REPLACE(wo.work_order_no, 'DOM-', ''))) = UPPER(TRIM(REPLACE(t.work_order_no, 'DOM-', '')))
);

