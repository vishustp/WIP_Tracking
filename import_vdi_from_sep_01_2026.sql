INSERT INTO public.qc_inspections (
  work_order_id,
  process_route_id,
  inspection_date,
  inspected_pcs,
  inspected_mtr,
  inspected_mt,
  vdi_ok_pcs,
  vdi_ok_mtr,
  vdi_ok_mt,
  vdi_salvage_pcs,
  vdi_salvage_mtr,
  vdi_salvage_mt,
  vdi_rejection_pcs,
  vdi_rejection_mtr,
  vdi_rejection_mt,
  salvage_reasons,
  remarks
)
SELECT
  wo.id AS work_order_id,
  COALESCE(
    (SELECT rp.process_route_id FROM public.rolling_plans rp WHERE rp.work_order_id = wo.id ORDER BY rp.created_at DESC LIMIT 1),
    (SELECT pr.id FROM public.process_routes pr WHERE pr.route_code = 'CDS' LIMIT 1)
  ) AS process_route_id,
  t.inspection_date,
  t.insp_pcs,
  t.insp_pcs * public.wo_avg_length(wo.id) AS inspected_mtr,
  t.accept_mt AS inspected_mt,
  t.accept_pcs,
  t.accept_pcs * public.wo_avg_length(wo.id) AS vdi_ok_mtr,
  t.accept_mt AS vdi_ok_mt,
  t.salvage_pcs,
  t.salvage_pcs * public.wo_avg_length(wo.id) AS vdi_salvage_mtr,
  0 AS vdi_salvage_mt,
  t.reject_pcs,
  t.reject_pcs * public.wo_avg_length(wo.id) AS vdi_rejection_mtr,
  0 AS vdi_rejection_mt,
  CASE WHEN t.salvage_reason IS NOT NULL AND t.salvage_reason <> '' THEN jsonb_build_array(t.salvage_reason) ELSE '[]'::jsonb END AS salvage_reasons,
  TRIM(COALESCE('Heat: ' || t.heat_no || ' ' || COALESCE('Rej: ' || t.reject_reason, ''), '')) AS remarks
FROM temp_vdi_import t
JOIN public.work_orders wo ON (
  UPPER(TRIM(wo.work_order_no)) = UPPER(TRIM(t.work_order_no))
  OR UPPER(TRIM(wo.work_order_no)) = UPPER('DOM-' || LPAD(TRIM(t.work_order_no), 5, '0'))
  OR UPPER(TRIM(REPLACE(wo.work_order_no, 'DOM-', ''))) = UPPER(TRIM(REPLACE(t.work_order_no, 'DOM-', '')))
  OR UPPER(TRIM(REPLACE(wo.work_order_no, 'DOM-BHEL-', 'DOM-'))) = UPPER(TRIM(REPLACE(t.work_order_no, 'DOM-BHEL-', 'DOM-')))
  OR UPPER(TRIM(REPLACE(wo.work_order_no, 'DOM-BHEL-', ''))) = UPPER(TRIM(REPLACE(t.work_order_no, 'DOM-BHEL-', '')))
);

